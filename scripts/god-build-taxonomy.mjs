// Turns the page map (data/god-build/taxonomy.src.json: every new page beyond the state and
// province series, with its search evidence, collisions and release order) into
// data/god-build/extra-pages.json, which scripts/god-build-plan.mjs schedules after the series.
//
//   node scripts/god-build-taxonomy.mjs && node scripts/god-build-plan.mjs && node scripts/us-pages-plan.mjs
//
// Left out: gated pages (built only if a hub shows demand first) and tools (React pages, not
// guides). A hub is moved ahead of any page that names it as its parent, because the release
// job holds a page back until its hub is live.
import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

const ROOT = process.cwd()
const DIR = join(ROOT, 'data', 'god-build')
const tax = JSON.parse(readFileSync(join(DIR, 'taxonomy.src.json'), 'utf8'))

// the map's topic families -> the site's topic categories (GuideCluster in lib/guides.ts)
const CLUSTER = {
  spiders: 'spiders', scorpions: 'spiders', 'stinging-insects': 'wasps', flies: 'flies', mites: 'mites',
  household: 'household', fleas: 'household', 'kissing-bugs': 'household', bites: 'bites',
  ticks: 'ticks', mosquitoes: 'mosquitoes', 'bed-bugs': 'bed-bugs', ants: 'ants', cockroaches: 'cockroaches', garden: 'garden',
  mice: 'mice', // the rat and mouse pages added from data/god-build/next-50.json (Oct 16, 2026)
}

const keep = tax.pages.filter((p) => !p.gate && (p.role === 'page' || p.role === 'hub'))
const skipped = tax.pages.filter((p) => !keep.includes(p)).map((p) => `${p.path} (${p.gate ? 'gated' : p.role})`)
keep.sort((a, b) => a.releaseOrder - b.releaseOrder)

// a hub goes no later than the first page that hangs off it
const order = [...keep]
for (const hub of keep.filter((p) => p.role === 'hub')) {
  const first = order.findIndex((p) => p.parent?.href === hub.path)
  const at = order.indexOf(hub)
  if (first !== -1 && first < at) { order.splice(at, 1); order.splice(first, 0, hub) }
}

const pages = order.map((p) => {
  const cluster = CLUSTER[p.cluster]
  if (!cluster) throw new Error(`${p.slug}: no topic category for family "${p.cluster}"`)
  return {
    slug: p.slug,
    section: p.section,
    role: p.role,
    cluster,
    ...(p.audience === 'ca' && { audience: 'ca' }),
    ...(p.audience === 'na' && { audience: 'na' }),
    keyword: p.keyword,
    alsoTargets: p.alsoTargets || [],
    h1Hint: p.title,
    metaTitleHint: p.metaTitle,
    scope: p.scope,
    pageType: p.pageType,
    flags: p.flags || [],
    minWords: p.minWords || 1500,
    minExisting: p.role === 'hub' ? 3 : 2,
    parent: p.parent || null,
    mustLink: p.mustLink || [],
    pairWith: p.pairWith || null,
    collisions: p.collisions || [],
    family: p.family,
    priority: p.priority,
  }
})

writeFileSync(join(DIR, 'extra-pages.json'), JSON.stringify({
  _readme: 'GENERATED by scripts/god-build-taxonomy.mjs from data/god-build/taxonomy.src.json. Edit that, not this. Scheduled after the state and province series by scripts/god-build-plan.mjs.',
  pages,
}, null, 1) + '\n')
const by = {}
for (const p of pages) by[p.cluster] = (by[p.cluster] || 0) + 1
console.log(`extra-pages.json: ${pages.length} pages (${pages.filter((p) => p.role === 'hub').length} hubs) | ${Object.entries(by).map(([k, v]) => `${k} ${v}`).join(', ')}`)
if (skipped.length) console.log(`not scheduled: ${skipped.join('; ')}`)
