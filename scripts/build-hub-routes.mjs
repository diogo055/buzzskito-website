// Hub pages carry no display ads (owner, Oct 20, 2026: "don't put ads on the main pages where it
// lists all the other pages"). This writes lib/hub-routes.json with every guide hub: each pillar
// guide, and every page another guide names as its `parent` (the state, province and bite hubs).
// lib/ads.ts reads it, scripts/check-ads.mjs re-computes it and fails the build when it is stale,
// and scripts/us-pages-register.mjs runs this on every release, so a new hub is ad-free from day one.
// The hand-made hubs (the index pages and the product-guide hubs) are listed in lib/ad-routes.json.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

export function computeHubPaths() {
  const dir = join(ROOT, 'content', 'guides')
  const paths = new Set()
  const live = new Map()
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const g = JSON.parse(readFileSync(join(dir, f), 'utf8'))
    live.set(g.slug, g)
    if (g.kind === 'pillar') paths.add(`/${g.section ?? 'learn'}/${g.slug}`)
    const parent = g.parent && typeof g.parent === 'object' ? g.parent.href : g.parent
    if (typeof parent === 'string' && parent.startsWith('/')) paths.add(parent.replace(/\/+$/, ''))
  }
  // The release plan marks hub pages with role "hub" (bug bites, spiders, fleas, the state and
  // province series ...): count each one as soon as its guide is live.
  const plan = JSON.parse(readFileSync(join(ROOT, 'data', 'god-build', 'plan.src.json'), 'utf8'))
  const entries = Array.isArray(plan) ? plan : plan.pages || plan.items || Object.values(plan)
  for (const e of entries) {
    if (!e || typeof e !== 'object' || !/hub/i.test(String(e.role || ''))) continue
    const g = live.get(e.slug)
    if (g) paths.add(`/${g.section ?? (g.kind === 'pillar' ? 'learn' : 'blog')}/${g.slug}`)
  }
  return [...paths].sort()
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const paths = computeHubPaths()
  const out = {
    _readme: 'GENERATED by scripts/build-hub-routes.mjs (run by the register script). Guide hub pages: pillars and every page another guide names as its parent. lib/ads.ts keeps display ads off them. Do not edit by hand.',
    paths,
  }
  writeFileSync(join(ROOT, 'lib', 'hub-routes.json'), JSON.stringify(out, null, 2) + '\n')
  console.log(`hub routes: ${paths.length} guide hubs -> lib/hub-routes.json`)
}
