// Wires the North American guides (content/guides/*.json) into the site. Safe to re-run.
//
//   node scripts/us-pages-register.mjs
//
// For every guide JSON it:
//   1. writes the route file (app/blog/<slug>/page.tsx or app/learn/<slug>/page.tsx)
//   2. rewrites the NEW_BLOGS_US_GUIDES block in lib/constants.ts (the sitemap and the blog
//      index both read it, and scripts/check-registered.mjs fails the build without it)
//   3. rewrites lib/us-guide-routes.ts (which guides hide the phone "Get a quote" bar)
//   4. writes new-urls.txt, build-manifest.json and reports/us_pages_media_needed.md
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'fs'
import { join } from 'path'

const ROOT = process.cwd()
const GUIDES = join(ROOT, 'content', 'guides')
const plan = JSON.parse(readFileSync(join(ROOT, 'data', 'us-pages', 'plan.json'), 'utf8'))
const kw = JSON.parse(readFileSync(join(ROOT, 'data', 'us-pages', 'keywords.json'), 'utf8'))
const byRank = Object.fromEntries(kw.map((k) => [Number(k.rank), k]))
const planByPath = Object.fromEntries(plan.pages.map((p) => [p.path, p]))
const q = (s) => JSON.stringify(s) // double-quoted, escaped: safe to paste into TS

const LINK = /\[([^\]]+)\]\(([^)\s]+)\)/g
const strip = (s) => String(s).replace(LINK, '$1').replace(/\*+/g, '')
const count = (s) => (strip(s).match(/[A-Za-z0-9][A-Za-z0-9'’%°/.-]*/g) || []).length
const texts = (b) => (b.type === 'ul' || b.type === 'ol' ? b.items : b.type === 'table' ? [...b.head, ...b.rows.flat(), b.caption || ''] : b.type === 'callout' ? [b.title || '', b.text] : b.type === 'media' ? [] : [b.text])

const guides = readdirSync(GUIDES).filter((f) => f.endsWith('.json')).map((f) => ({ file: f, g: JSON.parse(readFileSync(join(GUIDES, f), 'utf8')) }))
  .map(({ file, g }) => ({ file, g, path: g.kind === 'pillar' ? `/learn/${g.slug}` : `/blog/${g.slug}` }))
  .filter((x) => planByPath[x.path])
const CLUSTER_ORDER = ['bed-bugs', 'ants', 'mice', 'cockroaches', 'mosquitoes', 'ticks', 'pest-control']
guides.sort((a, b) => CLUSTER_ORDER.indexOf(a.g.cluster) - CLUSTER_ORDER.indexOf(b.g.cluster) || plan.pages.indexOf(planByPath[a.path]) - plan.pages.indexOf(planByPath[b.path]))

// ── 1. route files ──────────────────────────────────────────────────────────────
let routesWritten = 0
for (const { file, g } of guides) {
  const dir = join(ROOT, 'app', g.kind === 'pillar' ? 'learn' : 'blog', g.slug)
  mkdirSync(dir, { recursive: true })
  const name = g.slug.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('')
  const src = `import type { Metadata } from 'next'
import GuidePage from '@/components/GuidePage'
import { guideMetadata, type Guide } from '@/lib/guides'
import data from '@/content/guides/${file}'

// North American guide (Oct 2026). The words live in content/guides/${file}: edit them there.
// This file only connects that content to the shared template (components/GuidePage.tsx).
const guide = data as unknown as Guide

export const metadata: Metadata = guideMetadata(guide)

export default function ${name}${g.kind === 'pillar' ? 'Hub' : 'Guide'}Page() {
  return <GuidePage guide={guide} />
}
`
  const target = join(dir, 'page.tsx')
  if (!existsSync(target) || readFileSync(target, 'utf8') !== src) { writeFileSync(target, src); routesWritten++ }
}

// ── 2. lib/constants.ts block ───────────────────────────────────────────────────
const spokes = guides.filter((x) => x.g.kind === 'spoke')
const START = '// ── US-GUIDES:START (generated by scripts/us-pages-register.mjs — do not edit by hand) ──'
const END = '// ── US-GUIDES:END ──'
const block = `${START}
// North American pest guides, Oct 2026. Content: content/guides/<slug>.json. Rendered by
// components/GuidePage.tsx. \`cluster\` groups them on the blog index.
export const NEW_BLOGS_US_GUIDES = [
${spokes.map(({ g }) => `  { slug: ${q(g.slug)}, title: ${q(g.h1)}, excerpt: ${q(g.excerpt)}, date: ${q(g.datePublished)}, cluster: ${q(g.cluster)} },`).join('\n')}
]
${END}`
const constantsPath = join(ROOT, 'lib', 'constants.ts')
let constants = readFileSync(constantsPath, 'utf8')
const eol = constants.includes('\r\n') ? '\r\n' : '\n'
const blockEol = block.replace(/\n/g, eol)
if (constants.includes(START)) constants = constants.slice(0, constants.indexOf(START)) + blockEol + constants.slice(constants.indexOf(END) + END.length)
else constants = constants.replace(/\s*$/, '') + eol + eol + blockEol + eol
writeFileSync(constantsPath, constants)

// ── 3. lib/us-guide-routes.ts ───────────────────────────────────────────────────
const adjacent = guides.filter((x) => !['mosquitoes', 'ticks'].includes(x.g.cluster)).map((x) => x.path)
writeFileSync(join(ROOT, 'lib', 'us-guide-routes.ts'), `// GENERATED by scripts/us-pages-register.mjs — do not edit by hand.
// North American guides about pests BuzzSkito does not treat. The phone "Get a free quote"
// bar is hidden on them, for the same reason it is hidden on the older adjacent-pest pages
// (lib/adjacent-pest-routes.ts): the page itself says we do not offer that service.
// These pages are rendered by components/GuidePage.tsx, so the grep that regenerates
// adjacent-pest-routes.ts cannot see them. That is why they live in their own file.
export const US_GUIDE_ADJACENT_ROUTES = new Set<string>([
${adjacent.map((p) => `  ${q(p)},`).join('\n')}
])
`)

// ── 3b. lib/us-guide-built.ts: which planned pages exist yet ────────────────────
// A guide may link to a planned page that has not been written. GuidePage renders such a
// link as plain text until its target exists, so a page that fails or lags never leaves
// broken links behind. Re-running this script after adding a page lights the links up.
const HUBS_EXTRA = ['/pest-product-guides/ant-control', '/pest-product-guides/cockroach-control']
const plannedAll = [...plan.pages.map((p) => p.path), ...HUBS_EXTRA]
const builtAll = [...guides.map((x) => x.path), ...HUBS_EXTRA.filter((h) => existsSync(join(ROOT, 'app', h.slice(1), 'page.tsx')))]
writeFileSync(join(ROOT, 'lib', 'us-guide-built.ts'), `// GENERATED by scripts/us-pages-register.mjs — do not edit by hand.
// Every page planned for the Oct 2026 North American guides, and the ones that exist so far.
export const US_GUIDE_PLANNED = new Set<string>([
${plannedAll.map((p) => `  ${q(p)},`).join('\n')}
])
export const US_GUIDE_BUILT = new Set<string>([
${builtAll.map((p) => `  ${q(p)},`).join('\n')}
])
`)

// ── 4. indexing package ─────────────────────────────────────────────────────────
const pathsBuilt = new Set(guides.map((x) => x.path))
const inbound = Object.fromEntries(guides.map((x) => [x.path, 0]))
const linksOf = {}
for (const { g, path } of guides) {
  const hrefs = new Set()
  for (const t of [...g.body.flatMap(texts), g.quickAnswer.lead, ...g.quickAnswer.bullets, ...(g.facts ? g.facts.rows.flat() : [])]) for (const m of String(t).matchAll(LINK)) if (m[2].startsWith('/')) hrefs.add(m[2].replace(/[#?].*$/, ''))
  linksOf[path] = hrefs
  for (const h of hrefs) if (h in inbound && h !== path) inbound[h]++
}
const wordsOf = (g) => g.body.flatMap(texts).reduce((n, t) => n + count(t), 0)

const pillars = guides.filter((x) => x.g.kind === 'pillar')
const ranked = [...spokes].sort((a, b) => planByPath[b.path].projClicks - planByPath[a.path].projClicks)
const SITE = 'https://buzzskito.ca'
writeFileSync(join(ROOT, 'new-urls.txt'), [
  '# New pages, in the order to request indexing in Google Search Console (URL Inspection > Request indexing).',
  '# 1. The four hub pages', ...pillars.map((x) => SITE + x.path),
  '# 2. Extra product-guide hubs', `${SITE}/pest-product-guides/ant-control`, `${SITE}/pest-product-guides/cockroach-control`,
  '# 3. The 25 guides with the largest search demand', ...ranked.slice(0, 25).map((x) => SITE + x.path),
  '# 4. The rest', ...ranked.slice(25).map((x) => SITE + x.path), '',
].join('\n'))

const rows = []
for (const { g, path } of guides) {
  const p = planByPath[path]
  const kws = p.ranks.length ? p.ranks.map((r) => byRank[r]) : [{ rank: null, keyword: p.keyword, us_volume: null, proj_clicks_mo: null }]
  kws.forEach((k, i) => rows.push({ rank: k.rank ? Number(k.rank) : null, keyword: k.keyword, us_volume: k.us_volume ? Number(k.us_volume) : null, url: path, action: i === 0 ? 'new' : 'merged', mergedInto: i === 0 ? undefined : path, reason: i === 0 ? undefined : 'Same search intent as the page’s primary keyword; one page answers both.', kind: g.kind, cluster: g.cluster, title: g.metaTitle, wordCount: wordsOf(g), faqs: g.faqs.length, sources: g.sources.length, inboundFromNewPages: inbound[path], outboundInternalLinks: linksOf[path].size, status: 'built' }))
}
for (const m of plan.merged) rows.push({ rank: m.rank, keyword: byRank[m.rank].keyword, us_volume: Number(byRank[m.rank].us_volume), url: m.into, action: 'merged', mergedInto: m.into, reason: m.why, status: 'existing page' })
for (const b of plan.broaden) rows.push({ rank: b.rank, keyword: byRank[b.rank].keyword, us_volume: Number(byRank[b.rank].us_volume), url: b.page, action: 'broadened', status: existsSync(join(ROOT, 'data', 'us-pages', 'broaden-done.json')) && JSON.parse(readFileSync(join(ROOT, 'data', 'us-pages', 'broaden-done.json'), 'utf8')).includes(b.page) ? 'broadened' : 'pending' })
const notBuilt = plan.pages.filter((p) => !pathsBuilt.has(p.path))
for (const p of notBuilt) rows.push({ rank: p.ranks[0] ?? null, keyword: p.keyword, url: p.path, action: 'new', status: 'not built' })
rows.sort((a, b) => (a.rank ?? 0) - (b.rank ?? 0))
writeFileSync(join(ROOT, 'build-manifest.json'), JSON.stringify({
  generated: new Date().toISOString().slice(0, 10),
  summary: { keywords: 100, newPagesBuilt: guides.length, hubPages: pillars.length, guides: spokes.length, broadened: plan.broaden.length, mergedIntoExistingPages: plan.merged.length, mergedIntoNewPages: rows.filter((r) => r.action === 'merged' && r.status === 'built').length, notBuilt: notBuilt.length, internalLinksInNewPages: Object.values(linksOf).reduce((n, s) => n + s.size, 0) },
  pages: rows,
}, null, 1))

const media = []
for (const { g, path } of guides) for (const b of g.body) if (b.type === 'media') media.push({ path, needed: b.needed })
mkdirSync(join(ROOT, 'reports'), { recursive: true })
writeFileSync(join(ROOT, 'reports', 'us_pages_media_needed.md'), `# Photos and diagrams the new guides still need\n\n${media.length} images across ${new Set(media.map((m) => m.path)).size} pages. Each one is marked in the page's content file as a \`media\` block; nothing is shown on the page until a real image is added. Use your own photos or properly licensed ones.\n\n${[...new Set(media.map((m) => m.path))].map((p) => `## ${p}\n\n${media.filter((m) => m.path === p).map((m) => `- ${m.needed}`).join('\n')}`).join('\n\n')}\n`)

// ── 5. public/llms.txt: tell AI crawlers the library exists ─────────────────────
const llmsPath = join(ROOT, 'public', 'llms.txt')
if (existsSync(llmsPath)) {
  const HEAD = '## Pest Library — North American Guides (Oct 2026)'
  let llms = readFileSync(llmsPath, 'utf8')
  const leol = llms.includes('\r\n') ? '\r\n' : '\n'
  const at = llms.indexOf(HEAD)
  if (at >= 0) { const next = llms.indexOf(`${leol}## `, at + HEAD.length); llms = llms.slice(0, at) + (next >= 0 ? llms.slice(next + leol.length) : '') }
  const NAMES = { 'bed-bugs': 'Bed bugs', ants: 'Ants', mice: 'Mice', cockroaches: 'Cockroaches', mosquitoes: 'Mosquitoes', ticks: 'Ticks', 'pest-control': 'Hiring and DIY pest control' }
  const section = [HEAD, 'Source-cited identification and how-to guides written for readers in the United States and Canada. No product links. Each guide lists its government and university sources. BuzzSkito treats mosquitoes and ticks only; the guides on other pests are research, not a service.', '',
    ...pillars.map(({ g, path }) => `- ${g.h1}: ${SITE}${path} — complete reference (hub page)`),
    ...CLUSTER_ORDER.flatMap((c) => { const list = spokes.filter((x) => x.g.cluster === c); return list.length ? ['', `### ${NAMES[c]}`, ...list.map(({ g, path }) => `- ${g.h1}: ${SITE}${path}`)] : [] }), '', ''].join(leol)
  const before = llms.indexOf('## Press Coverage')
  llms = before >= 0 ? llms.slice(0, before) + section + llms.slice(before) : llms.replace(/\s*$/, '') + leol + leol + section
  writeFileSync(llmsPath, llms)
}

console.log(`guides: ${guides.length} (${pillars.length} hubs, ${spokes.length} guides) | route files written: ${routesWritten} | not built: ${notBuilt.length} | media placeholders: ${media.length}`)
const low = Object.entries(inbound).filter(([, n]) => n < 3)
if (low.length) console.log('under 3 inbound links from new pages:', low.map(([p, n]) => `${p} (${n})`).join(', '))
