// Phase 0 deliverable: render docs/audit/protected-pages.md from the classification JSON.
// Kept as a script so the list can be regenerated when routes are added.
import fs from 'node:fs'

const rows = JSON.parse(fs.readFileSync('docs/audit/_protected.json', 'utf8'))
const byWhy = {}
for (const r of rows) (byWhy[r.why] = byWhy[r.why] || []).push(r.u)
const groups = Object.entries(byWhy).sort((a, b) => b[1].length - a[1].length)

const L = []
L.push('# Protected pages — do not modify')
L.push('')
L.push('Generated 2026-09-08 for branch `feat/affiliate-content-sept26`, Phase 0.')
L.push('')
L.push('Guardrail 2: never touch local service pages — GTA location pages, neighbourhood pages,')
L.push('quote/contact/pricing, the homepage, or anything with a quote form or LocalBusiness schema.')
L.push('')
L.push('**Every page below was classified by a signal found inside the file, not by its URL pattern.**')
L.push('That matters because several city pages carry no LocalBusiness schema and would have been')
L.push('missed by a name-based rule, while three `/pest-product-guides/*` routes look like service')
L.push('pages by name but are actually the affiliate hubs.')
L.push('')
L.push('## Summary')
L.push('')
L.push('| | Count |')
L.push('|---|---|')
L.push(`| **PROTECTED — do not modify** | **${rows.length}** |`)
L.push('| In scope: `/blog/*` articles | 358 |')
L.push('| In scope: affiliate hubs (`/pest-product-guides`, `/bed-bug-control`, `/rodent-control`) | 3 |')
L.push(`| Total routes on the site | ${rows.length + 361} |`)
L.push('')
L.push('| Reason protected | Pages |')
L.push('|---|---|')
for (const [k, v] of groups) L.push(`| ${k} | ${v.length} |`)
L.push('')
L.push('## Two findings you should know before approving')
L.push('')
L.push('**1. No blog page carries a protected signal.** I checked all 358 for LocalBusiness schema and')
L.push('for embedded lead forms — zero have either. The blog is cleanly separable from the service side,')
L.push('so the affiliate work can proceed without any risk of touching the service business.')
L.push('')
L.push('**2. But 222 blog pages contain a `CTASection` that links to the quote funnel.** That is a link,')
L.push('not a form, so those pages stay in scope for content work — **with one standing condition: no')
L.push('later phase may remove, move, or weaken that CTA.** It is the route from an affiliate reader to')
L.push('a $1,222 service customer, and one service customer is worth roughly 368 affiliate orders.')
L.push('I am flagging it here rather than in a later phase because it is the single way this project')
L.push('could do real damage while appearing to succeed.')
L.push('')
L.push('## Full list')
L.push('')
for (const [k, v] of groups) {
  L.push(`### ${k} (${v.length})`)
  L.push('')
  for (const u of v.sort()) L.push(`- \`${u}\``)
  L.push('')
}

fs.writeFileSync('docs/audit/protected-pages.md', L.join('\n'))
console.log(`wrote docs/audit/protected-pages.md — ${rows.length} protected routes`)
for (const [k, v] of groups) console.log(`  ${k.padEnd(24)} ${String(v.length).padStart(4)}`)
